function chartData = create_model_comparison_charts()
%CREATE_MODEL_COMPARISON_CHARTS Plot completed MATLAB trials without refitting.
folder=fileparts(mfilename('fullpath'));
source=fullfile(folder,'..','local_model_comparison','results');
families=readtable(fullfile(source,'comparison_with_boosted_reference.csv'),TextType='string');
blends=readtable(fullfile(source,'blend_comparison_results.csv'),TextType='string');
history=readtable(fullfile(source,'history_comparison_results.csv'),TextType='string');
assert(height(families)==7 && height(blends)==3 && height(history)==3);
assert(all(isfinite(families.PooledRMSE)) && all(isfinite(history.PooledRMSE)));
familyLabels=["LSBoost (tuned)","Random forest","Bagged trees", ...
    "Ridge regression","Approx. Gaussian kernel","Neural network, 100 iterations", ...
    "Neural network, 1,000 iterations"]';
ids=["L07","RF100","BAG100","RIDGE001","KERNEL1024","NET64x32","NET64x32_1000"]';
[found,index]=ismember(ids,families.ConfigID);assert(all(found));families=families(index,:);
notes=repmat("One tested configuration",7,1);
notes(1)="Selected from eight LSBoost configurations";
notes(5)="Fixed optimization budget; convergence not established on both folds";
notes(6:7)="Iteration limit reached on both folds";
chartData=table(familyLabels,repmat("Model family screening",7,1),ids, ...
    families.PooledRMSE,families.PooledMAE,families.Year4RMSE,families.Year5RMSE,notes, ...
    'VariableNames',{'Model','Stage','ConfigID','PooledRMSE','PooledMAE', ...
    'Year4RMSE','Year5RMSE','Notes'});
for j=1:height(blends)
    label=sprintf('LSBoost %.0f%% + forest %.0f%%', ...
        100*(1-blends.ForestWeight(j)),100*blends.ForestWeight(j));
    chartData(end+1,:)={string(label),"Prediction blending",blends.ConfigID(j), ...
        blends.PooledRMSE(j),blends.PooledMAE(j),blends.Year4RMSE(j),blends.Year5RMSE(j), ...
        "Preset blend weights compared on model-selection folds"}; %#ok<AGROW>
end
historyIDs=["HISTORY_LATEST","HISTORY_DIRECT","HISTORY_RESIDUAL"];
historyLabels=["Latest earlier EUI + fallback","LSBoost with history, direct EUI", ...
    "LSBoost with history, predicted change"];
for j=1:numel(historyIDs)
    row=history(history.Method==historyIDs(j),:);assert(height(row)==1);
    chartData(end+1,:)={historyLabels(j),"Building history",historyIDs(j), ...
        row.PooledRMSE,row.PooledMAE,row.Year4RMSE,row.Year5RMSE, ...
        "Earlier fitting years only; missing-history treatment documented in RESULTS.md"}; %#ok<AGROW>
end
writetable(chartData,fullfile(folder,'model_comparison_data.csv'));
save(fullfile(folder,'model_comparison_data.mat'),'chartData','families','blends','history');

colors=repmat([0.50,0.58,0.64],6,1);colors(1,:)=[0.02,0.46,0.45];
colors(6,:)=[0.82,0.44,0.15];
fig=drawBars(familyLabels(1:6),families.PooledRMSE(1:6),colors,110, ...
    'MATLAB model family comparison', ...
    'Same 59 source predictors. Forward validation on years 4 and 5. Lower RMSE is better.', ...
    {'LSBoost was tuned across 8 settings; other families started with one setting each.', ...
    'Neural network reached its iteration cap. Its 1,000-iteration follow-up scored 297.21 RMSE.', ...
    'Kernel results reflect a fixed solver budget. These trials do not rule out a model family.'});
writeFigure(fig,folder,'01_model_families');

chosen=["L07","BLEND_RF050","HISTORY_LATEST","HISTORY_DIRECT","HISTORY_RESIDUAL"];
[found,index]=ismember(chosen,chartData.ConfigID);assert(all(found));
selected=chartData(index,:);
labels=["Tuned LSBoost, baseline","50/50 LSBoost + forest", ...
    "Latest earlier EUI + fallback","LSBoost + history, direct EUI", ...
    "LSBoost + history, predicted change"]';
colors=repmat([0.50,0.58,0.64],5,1);colors(5,:)=[0.02,0.46,0.45];
reduction=100*(selected.PooledRMSE(1)-selected.PooledRMSE(5))/selected.PooledRMSE(1);
fig=drawBars(labels,selected.PooledRMSE,colors,50, ...
    'Building history improved validation performance', ...
    sprintf('History residual LSBoost reduced pooled RMSE by %.1f%% versus tuned baseline LSBoost.',reduction), ...
    {'Both graphs use the same 31,254 historical validation rows, with the same temporal splits.', ...
    'History uses strictly earlier fitting labels. The selected method uses an ensemble fallback without history.', ...
    'Kaggle scores use different test rows and are excluded from this comparison.'});
writeFigure(fig,folder,'02_building_history');
disp(chartData);
end

function fig = drawBars(labels,values,colors,xMaximum,heading,subheading,footnotes)
fig=figure('Color','w','Position',[80,80,1550,880],'Name',heading,'NumberTitle','off');
ax=axes(fig,'Position',[0.33,0.24,0.60,0.58]);
bars=barh(ax,1:numel(values),values,0.62,'FaceColor','flat','EdgeColor','none');
ax.Color='w';ax.XColor=[0.12,0.16,0.20];ax.YColor=[0.12,0.16,0.20];
ax.GridColor=[0.45,0.50,0.55];
bars.CData=colors;ax.YDir='reverse';ax.YTick=1:numel(values);ax.YTickLabel=labels;
ax.FontName='Arial';ax.FontSize=15;ax.TickLabelInterpreter='none';
ax.TickLength=[0,0];ax.Box='off';ax.XGrid='on';ax.YGrid='off';
ax.GridAlpha=0.13;ax.XLim=[0,xMaximum];ax.YLim=[0.4,numel(values)+0.6];
xlabel(ax,'Pooled validation RMSE (original site_eui scale)','FontSize',15);
for j=1:numel(values)
    text(ax,values(j)+0.012*xMaximum,j,sprintf('%.2f',values(j)), ...
        'FontName','Arial','FontSize',17,'FontWeight','bold', ...
        'Color',[0.08,0.12,0.16],'VerticalAlignment','middle');
end
annotation(fig,'textbox',[0.045,0.905,0.91,0.065],'String',heading, ...
    'FontName','Arial','FontSize',27,'FontWeight','bold','Color',[0.08,0.12,0.16], ...
    'EdgeColor','none','Interpreter','none');
annotation(fig,'textbox',[0.045,0.85,0.92,0.05],'String',subheading, ...
    'FontName','Arial','FontSize',16,'Color',[0.18,0.23,0.27], ...
    'EdgeColor','none','Interpreter','none');
annotation(fig,'textbox',[0.045,0.025,0.92,0.14],'String',footnotes, ...
    'FontName','Arial','FontSize',13,'Color',[0.25,0.30,0.34], ...
    'EdgeColor','none','Interpreter','none');
end

function writeFigure(fig,folder,stem)
exportgraphics(fig,fullfile(folder,[stem,'.png']),'Resolution',180, ...
    'BackgroundColor','white','Padding',24);
exportgraphics(fig,fullfile(folder,[stem,'.svg']),'ContentType','vector', ...
    'BackgroundColor','white','Padding',24);
savefig(fig,fullfile(folder,[stem,'.fig']));
end
