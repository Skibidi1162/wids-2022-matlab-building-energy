function [model,diagnostics] = wids_fit_candidate(config,X,y)
%WIDS_FIT_CANDIDATE Fit fixed CPU budgets without using validation targets.
rng(42,'twister');
p = config.Parameters;
switch config.Family
    case {"forest","bagged"}
        tree = templateTree(MaxNumSplits=p.MaxNumSplits,MinLeafSize=p.MinLeafSize, ...
            NumVariablesToSample=p.Mtry,Reproducible=true);
        trained = fitrensemble(X,y,Method='Bag',NumLearningCycles=p.Trees, ...
            Learners=tree,Options=statset('UseParallel',false));
        model = compact(trained);
        diagnostics = struct('RequestedTrees',p.Trees,'CompletedTrees',numel(model.Trained));
    case "net"
        model = fitrnet(X,y,LayerSizes=p.LayerSizes,Lambda=p.Lambda, ...
            Activations='relu',IterationLimit=p.IterationLimit, ...
            Standardize=false,StandardizeResponses=true,Verbose=0);
        diagnostics = struct('ConvergenceInfo',model.ConvergenceInfo, ...
            'TrainingHistory',model.TrainingHistory);
    case "kernel"
        [model,diagnostics] = fitrkernel(X,y,Learner='leastsquares', ...
            NumExpansionDimensions=p.ExpansionDimensions,KernelScale=p.KernelScale, ...
            Lambda=1/numel(y),BlockSize=p.BlockSizeMB,IterationLimit=p.IterationLimit, ...
            Standardize=false,Verbose=0);
    case "ridge"
        [model,diagnostics] = fitrlinear(X,y,Learner='leastsquares', ...
            Regularization='ridge',Lambda=p.Lambda,Solver='lbfgs', ...
            IterationLimit=p.IterationLimit);
    otherwise
        error('WiDS:ModelFamily','Unknown model family.');
end
end
