function [model,diagnostics] = nscc_fit(config,X,y,seed)
%NSCC_FIT Fixed bounded CPU configurations, with no validation-driven fitting.
rng(seed,'twister');
p = config.Parameters;
switch config.Family
    case 'linear'
        [model,diagnostics] = fitrlinear(X,y,'Learner','leastsquares', ...
            'Regularization','ridge','Lambda',p.Lambda, ...
            'Solver','lbfgs','IterationLimit',p.IterationLimit);
    case 'forest'
        if ischar(p.Mtry) || isstring(p.Mtry)
            assert(strcmp(p.Mtry,'all'),'WiDS:Mtry','Invalid Mtry value.');
            mtry='all';
        else
            mtry=p.Mtry;
        end
        t = templateTree('Type','regression','MinLeafSize',p.MinLeafSize, ...
            'MaxNumSplits',p.MaxNumSplits,'NumVariablesToSample',mtry, ...
            'Reproducible',true,'Surrogate','off','Prune','off');
        model = fitrensemble(X,y,'Method','Bag','NumLearningCycles',p.Trees, ...
            'Learners',t,'CategoricalPredictors', ...
            {'State_Factor','building_class','facility_type'}, ...
            'Options',statset('UseParallel',false));
        diagnostics = struct('Trees',numel(model.Trained), ...
            'CompletedRequestedTrees',numel(model.Trained)==p.Trees);
    case 'kernel'
        [model,diagnostics] = fitrkernel(X,y,'Learner','leastsquares', ...
            'NumExpansionDimensions',p.ExpansionDimensions, ...
            'KernelScale',p.KernelScale,'Lambda',p.Lambda, ...
            'BlockSize',p.BlockSizeMB,'IterationLimit',p.IterationLimit, ...
            'Standardize',false,'Verbose',1);
    case 'net'
        model = fitrnet(X,y,'LayerSizes',reshape(p.LayerSizes,1,[]), ...
            'Activations','relu','Lambda',p.Lambda, ...
            'IterationLimit',p.IterationLimit,'Standardize',false,'Verbose',1);
        diagnostics = struct('ConvergenceInfo',model.ConvergenceInfo, ...
            'TrainingHistory',model.TrainingHistory);
    otherwise
        error('WiDS:Family','Unknown model family %s.',config.Family);
end
end
