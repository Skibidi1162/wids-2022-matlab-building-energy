function nscc_selftest
%NSCC_SELFTEST Synthetic leakage and unknown-category checks; no model fitting.
n = 6;
A = table((1:n)',[1;1;2;2;3;3],repmat("S1",n,1), ...
    repmat("Commercial",n,1),["A";"A";"B";"B";"A";"B"], ...
    [0;1940;1950;1960;NaN;1980],[NaN;60;70;80;90;50], ...
    (10:10:60)',ones(n,1),zeros(n,1),zeros(n,1),zeros(n,1),zeros(n,1), ...
    'VariableNames',{'id','Year_Factor','State_Factor','building_class', ...
    'facility_type','year_built','energy_star_rating','site_eui','floor_area', ...
    'direction_max_wind_speed','direction_peak_wind_speed','max_wind_speed','days_with_fog'});
B = A(1:2,:); B.id = [100;101]; B.Year_Factor(:)=4;
B.facility_type(:) = "unseen"; B.year_built(:)=0;
[Ac,Bc,p] = wids_clean_split(A,B);
mutated = B;
mutated.site_eui(:) = 1e9; mutated.energy_star_rating(:)=1e8;
mutated.floor_area(:)=1e6; mutated.State_Factor(:)="new_state";
[Ac2,Bc2,p2] = wids_clean_split(A,mutated);
assert(isequaln(Ac,Ac2) && isequaln(p,p2), ...
    'WiDS:Selftest','Validation data leaked into fitting cleaning.');
assert(all(string(Bc.facility_type)=="__unknown__") && ...
    isequal(Bc.site_eui,B.site_eui) && all(Bc.year_built_missing), ...
    'WiDS:Selftest','Unknown mapping, missing flags, or targets changed.');
names = ["State_Factor","facility_type","year_built", ...
    "energy_star_rating","floor_area","year_built_missing"];
[X,V,schema] = nscc_encode(Ac,Bc,names);
[X2,~,schema2] = nscc_encode(Ac2,Bc2,names);
assert(isequaln(X,X2) && isequaln(schema,schema2), ...
    'WiDS:Selftest','Validation data leaked into scaling or encoding.');
assert(all(isfinite(X(:))) && all(isfinite(V(:))) && ...
    schema.Numeric.floor_area.Std==1 && ...
    ~any(schema.CategoryLevels.facility_type=="unseen"), ...
    'WiDS:Selftest','Encoding or constant-column handling failed.');
assert(p.Medians.year_built==1955 && p.Medians.energy_star_rating==70, ...
    'WiDS:Selftest','Fitting medians do not match expected values.');
fprintf('Synthetic preprocessing self-test passed.\n');
end
