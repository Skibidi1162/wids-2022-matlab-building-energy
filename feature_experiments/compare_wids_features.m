%% Compare feature sets with the same model and the same year-6 holdout
% A first controlled experiment, not a tuned search or independent final test.
% This also recreates the existing cleaning and feature proposal.
widsComparisonScriptFolder = fileparts(mfilename('fullpath'));
run(fullfile(widsComparisonScriptFolder, 'engineer_wids_data.m'));

%% Construct the common baseline and the independent alternative
widsCompareBaselineTrain = removevars(widsTrainClean(widsFitMask,:), 'Year_Factor');
widsCompareBaselineValidation = removevars(widsTrainClean(widsValidationMask,:), 'Year_Factor');
[widsAlternativeModelTrain, widsAlternativeModelValidation, ...
    widsAlternativeTestFeatures, widsAlternativeParameters] = ...
    wids_alternative_features(widsTrainClean(widsFitMask,:), ...
    widsTrainClean(widsValidationMask,:), widsTestClean);
widsAlternativeTrainingData = removevars(widsAlternativeModelTrain, 'site_eui');
widsAlternativeValidationData = removevars(widsAlternativeModelValidation, 'site_eui');

widsCompareTrainSets = {removevars(widsCompareBaselineTrain, 'site_eui'), ...
    widsTrainingData, widsAlternativeTrainingData};
widsCompareValidationSets = {removevars(widsCompareBaselineValidation, 'site_eui'), ...
    widsValidationData, widsAlternativeValidationData};
widsFeatureSetNames = ["Cleaned baseline"; "Existing proposal"; "Alternative proposal"];

%% Fixed settings isolate the effect of feature construction
widsComparisonSettings = struct('Method', 'LSBoost', 'NumLearningCycles', 200, ...
    'LearnRate', 0.05, 'MaxNumSplits', 31, 'MinLeafSize', 20, 'Seed', 42);
widsComparisonTree = templateTree(MaxNumSplits=31, MinLeafSize=20, ...
    NumVariablesToSample='all', Reproducible=true);
widsComparisonModels = cell(3,1);
widsComparisonPredictions = zeros(numel(widsValidationOutput),3);
widsCompareRMSE = zeros(3,1);
widsCompareMAE = zeros(3,1);
widsCompareR2 = zeros(3,1);
widsCompareSeconds = zeros(3,1);
widsCompareFeatureCounts = zeros(3,1);
for widsSetIndex = 1:3
    rng(widsComparisonSettings.Seed, 'twister');
    fprintf('\nTraining %s with %d predictors...\n', ...
        widsFeatureSetNames(widsSetIndex), width(widsCompareTrainSets{widsSetIndex}));
    widsTimer = tic;
    widsComparisonModels{widsSetIndex} = fitrensemble( ...
        widsCompareTrainSets{widsSetIndex}, widsTrainingOutput, ...
        Method=widsComparisonSettings.Method, ...
        NumLearningCycles=widsComparisonSettings.NumLearningCycles, ...
        LearnRate=widsComparisonSettings.LearnRate, Learners=widsComparisonTree);
    widsCompareSeconds(widsSetIndex) = toc(widsTimer);
    widsPrediction = predict(widsComparisonModels{widsSetIndex}, ...
        widsCompareValidationSets{widsSetIndex});
    widsComparisonPredictions(:,widsSetIndex) = widsPrediction;
    widsError = widsPrediction - widsValidationOutput;
    widsCompareRMSE(widsSetIndex) = sqrt(mean(widsError.^2));
    widsCompareMAE(widsSetIndex) = mean(abs(widsError));
    widsCompareR2(widsSetIndex) = 1 - sum(widsError.^2) / ...
        sum((widsValidationOutput - mean(widsValidationOutput)).^2);
    widsCompareFeatureCounts(widsSetIndex) = width(widsCompareTrainSets{widsSetIndex});
    fprintf('%s: RMSE %.4f, MAE %.4f, training %.1f seconds.\n', ...
        widsFeatureSetNames(widsSetIndex), widsCompareRMSE(widsSetIndex), ...
        widsCompareMAE(widsSetIndex), widsCompareSeconds(widsSetIndex));
end

%% Export a small reviewable result table
widsFeatureComparison = table(widsFeatureSetNames, widsCompareFeatureCounts, ...
    widsCompareRMSE, widsCompareMAE, widsCompareR2, widsCompareSeconds, ...
    100*(widsCompareRMSE(1)-widsCompareRMSE)/widsCompareRMSE(1), ...
    'VariableNames', {'FeatureSet','Predictors','ValidationRMSE','ValidationMAE', ...
    'ValidationR2','TrainingSeconds','RMSEImprovementPercent'});
disp(widsFeatureComparison);
writetable(widsFeatureComparison, fullfile(widsComparisonScriptFolder, ...
    'wids_feature_comparison.csv'));
fprintf('All models used %d training rows and the same %d validation rows.\n', ...
    numel(widsTrainingOutput), numel(widsValidationOutput));
fprintf('Scores use original site_eui units. Kaggle test rows were not scored.\n');
