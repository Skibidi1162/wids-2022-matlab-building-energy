%% Bounded earlier-year check of baseline, full, and reduced feature sets
% Run the main ablation and reduced-subset confirmation first.
assert(exist('widsAblationConfirmedResults','var') == 1, ...
    'Run ablate_wids_features and confirm_wids_ablation_subset first.');
widsStabilityFolder = fileparts(mfilename('fullpath'));
widsStabilityFitRaw = widsAblationRaw(widsAblationRaw.Year_Factor<=3,:);
widsStabilityValidationRaw = widsAblationRaw(widsAblationRaw.Year_Factor==4,:);
[widsStabilityCleanFit,widsStabilityCleanValidation,widsStabilityCleaning] = ...
    wids_clean_split(widsStabilityFitRaw,widsStabilityValidationRaw);
[widsStabilityFit,widsStabilityValidation,~,widsStabilityParameters] = ...
    wids_alternative_features(widsStabilityCleanFit,widsStabilityCleanValidation, ...
    removevars(widsStabilityCleanValidation([],:),'site_eui'));
widsStabilityNames = {widsSubsetBaselineNames, ...
    widsAblationFitX.Properties.VariableNames,widsSubsetPredictorNames};
widsStabilityLabels = ["Cleaned baseline";"All six additions";"Reduced additions"];
widsStabilityModels = cell(3,1);
widsStabilityPredictions = zeros(height(widsStabilityValidation),3);
widsStabilityEarlierResults = table;
for widsStabilityIndex = 1:3
    rng(widsAblationSettings.Seed,'twister');
    widsStabilityTimer = tic;
    widsStabilityModel = fitrensemble( ...
        widsStabilityFit(:,widsStabilityNames{widsStabilityIndex}), ...
        widsStabilityFit.site_eui,Method=widsAblationSettings.Method, ...
        NumLearningCycles=widsAblationSettings.NumLearningCycles, ...
        LearnRate=widsAblationSettings.LearnRate,Learners=widsAblationTree);
    widsStabilitySeconds = toc(widsStabilityTimer);
    widsStabilityModels{widsStabilityIndex} = compact(widsStabilityModel);
    widsStabilityPredicted = predict(widsStabilityModel, ...
        widsStabilityValidation(:,widsStabilityNames{widsStabilityIndex}));
    assert(all(isfinite(widsStabilityPredicted)));
    widsStabilityPredictions(:,widsStabilityIndex) = widsStabilityPredicted;
    widsStabilityError = widsStabilityPredicted-widsStabilityValidation.site_eui;
    widsStabilityRow = table("1-3",4,widsStabilityLabels(widsStabilityIndex), ...
        height(widsStabilityFit),height(widsStabilityValidation), ...
        numel(widsStabilityNames{widsStabilityIndex}), ...
        sqrt(mean(widsStabilityError.^2)),mean(abs(widsStabilityError)), ...
        widsStabilitySeconds,'VariableNames',{'FitYears','ValidationYear', ...
        'FeatureSet','FitRows','ValidationRows','Predictors','RMSE','MAE','TrainingSeconds'});
    widsStabilityEarlierResults = [widsStabilityEarlierResults;widsStabilityRow]; %#ok<AGROW>
    writetable(widsStabilityEarlierResults, ...
        fullfile(widsStabilityFolder,'wids_stability_progress.csv'));
end
widsStabilityLaterIndices = [1,2,height(widsAblationConfirmedResults)];
widsStabilityLaterResults = table(repmat("1-4",3,1),repmat(5,3,1), ...
    widsStabilityLabels,repmat(numel(widsAblationFitY),3,1), ...
    repmat(numel(widsAblationValidationY),3,1), ...
    widsAblationConfirmedResults.Predictors(widsStabilityLaterIndices), ...
    widsAblationConfirmedResults.ValidationRMSE(widsStabilityLaterIndices), ...
    widsAblationConfirmedResults.ValidationMAE(widsStabilityLaterIndices), ...
    widsAblationConfirmedResults.TrainingSeconds(widsStabilityLaterIndices), ...
    'VariableNames',widsStabilityEarlierResults.Properties.VariableNames);
widsFeatureStability = [widsStabilityEarlierResults;widsStabilityLaterResults];
disp(widsFeatureStability);
writetable(widsFeatureStability, ...
    fullfile(widsStabilityFolder,'wids_feature_stability.csv'));

%% Pool squared errors across the two historical validation years
widsPooledRMSE = zeros(3,1);
widsPooledMAE = zeros(3,1);
for widsPoolIndex = 1:3
    widsPoolRows = widsFeatureStability.FeatureSet == widsStabilityLabels(widsPoolIndex);
    widsPoolWeights = widsFeatureStability.ValidationRows(widsPoolRows);
    widsPooledRMSE(widsPoolIndex) = sqrt(sum(widsPoolWeights .* ...
        widsFeatureStability.RMSE(widsPoolRows).^2) / sum(widsPoolWeights));
    widsPooledMAE(widsPoolIndex) = sum(widsPoolWeights .* ...
        widsFeatureStability.MAE(widsPoolRows)) / sum(widsPoolWeights);
end
widsPooledFeatureResults = table(widsStabilityLabels,widsPooledRMSE,widsPooledMAE, ...
    'VariableNames',{'FeatureSet','PooledRMSE','PooledMAE'});
disp(widsPooledFeatureResults);
writetable(widsPooledFeatureResults, ...
    fullfile(widsStabilityFolder,'wids_feature_pooled_results.csv'));
% Preserve a conservative provisional baseline for the next tuning stage.
% The full bundle remains a challenger because its earlier year-6 score was
% better; neither historical check is an independent final-performance test.
widsSelectedFeatureNames = widsSubsetBaselineNames;
writetable(table(string(widsSelectedFeatureNames(:)), ...
    'VariableNames',{'Predictor'}), ...
    wids_shared_file("wids_selected_baseline_features.csv"));
clear widsStabilityModel;
